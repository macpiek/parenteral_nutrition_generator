const fs = require("node:fs");
const path = require("node:path");

const rootDir = path.join(__dirname, "..");
const configPath = path.join(rootDir, "config.json");
const templatePath = path.join(rootDir, "szablon.xlsx");
const outputPath = path.join(rootDir, "embeddedAssets.js");

const config = JSON.parse(fs.readFileSync(configPath, "utf8"));
const templateBase64 = fs.readFileSync(templatePath).toString("base64");

const output = `/* Generated by scripts/build-standalone-assets.js.
 * This file lets index.html run directly from disk without a local server.
 */
(function (root) {
  root.PN_APP_CONFIG = ${JSON.stringify(config, null, 2)};
  root.PN_TEMPLATE_XLSX_BASE64 = "${templateBase64}";
})(typeof globalThis !== "undefined" ? globalThis : window);
`;

fs.writeFileSync(outputPath, output);
